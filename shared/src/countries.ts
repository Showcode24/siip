export type CountryCode = (typeof COUNTRY_CODES)[number];

export const NIGERIA: CountryCode = "NG";

const isCode = (v: string): v is CountryCode => (COUNTRY_CODES as readonly string[]).includes(v);
export const isCountryCode = isCode;

let names: Intl.DisplayNames | null = null;
/** "NG" → "Nigeria". Falls back to the code if the runtime has no region names. */
export function countryName(code: string): string {
  try {
    names ??= new Intl.DisplayNames(["en"], { type: "region" });
    return names.of(code) ?? code;
  } catch {
    return code === "XK" ? "Kosovo" : code;
  }
}

/** Every country as { code, name }, sorted by name. */
export function countryOptions(): Array<{ code: CountryCode; name: string }> {
  return COUNTRY_CODES.map((code) => ({ code, name: countryName(code) })).sort((a, b) =>
    a.name.localeCompare(b.name, "en"),
  );
}
